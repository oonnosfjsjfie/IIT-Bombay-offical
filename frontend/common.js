window.showStatus = function (kind, key, vars = {}) {
    const box = document.getElementById('statusIndicator');
    if (!box) return;
    if (!kind) {
        window.lastStatus = null;
        box.innerHTML = '';
        return;
    }
    window.lastStatus = { kind, key, vars };
    const div = document.createElement('div');
    div.style.cssText = STATUS_STYLES[kind] + 'padding:10px;border-radius:6px;font-size:13px;';
    div.textContent = t(key, vars);
    box.innerHTML = '';
    box.appendChild(div);
};

// ---------- Markdown → safe HTML ----------
window.renderMarkdown = function (text) {
    text = text || '';
    if (window.marked && window.DOMPurify) {
        return DOMPurify.sanitize(marked.parse(text));
    }
    const div = document.createElement('div');
    div.textContent = text;
    return div.innerHTML.replace(/\n/g, '<br>');
};

// ---------- AI translation of generated content ----------
window.translateText = async function (text, lang) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 90000);
    try {
        const res = await fetch(`${API_BASE}/api/translate`, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ text: text, target_language: lang }),
            signal: controller.signal
        });
        if (!res.ok) throw new Error(`Server error ${res.status}`);
        const data = await res.json();
        if (data.ok === false) throw new Error(data.text);
        return data.text;
    } finally {
        clearTimeout(timer);
    }
};

// map looks like { English: "...", Malayalam: "..." }. Fills in the missing language.
window.getLocalized = async function (map, lang) {
    if (map[lang]) return map[lang];
    const source = map.English || map.Malayalam || Object.values(map)[0];
    if (!source) return '';
    map[lang] = await translateText(source, lang);
    return map[lang];
};

// ---------- Apply UI text ----------
window.applyTexts = function (root = document) {
    const dict = I18N[window.neutrixLang];
    root.querySelectorAll('[data-i18n]').forEach(el => {
        const value = dict[el.dataset.i18n];
        if (value !== undefined) el.textContent = value;
    });
    root.querySelectorAll('[data-i18n-html]').forEach(el => {
        const value = dict[el.dataset.i18nHtml];
        if (value !== undefined) el.innerHTML = value;
    });
    root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = dict[el.dataset.i18nPlaceholder];
    });
    root.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = dict[el.dataset.i18nTitle];
    });
};

// Show navbar links only where there is something to open
window.updateNav = function () {
    const current = document.body.dataset.page;
    const hasReport = !!storeGet('neutrixReport');
    const hasSchedule = !!storeGet('neutrixSchedule');
    document.querySelectorAll('[data-nav]').forEach(link => {
        const target = link.dataset.nav;
        let show = target !== current;
        if (target === 'report' && !hasReport) show = false;
        if (target === 'schedule' && !hasSchedule) show = false;
        link.classList.toggle('hidden', !show);
    });
};

// ---------- Theme + language ----------
const themeBtn = document.getElementById('themeToggle');
const langBtn = document.getElementById('langToggle');

function updateThemeLabel() {
    const isDark = document.documentElement.getAttribute('data-theme') === 'dark';
    themeBtn.textContent = isDark ? t('lightMode') : t('darkMode');
}

function applyLanguage(lang) {
    window.neutrixLang = lang;
    document.documentElement.lang = lang === 'Malayalam' ? 'ml' : 'en';
    applyTexts();

    const titleKey = document.body.dataset.titleKey || 'pageTitle';
    document.title = I18N[lang][titleKey];
    langBtn.textContent = I18N[lang].langButton;
    updateThemeLabel();

    if (window.lastStatus) {
        showStatus(window.lastStatus.kind, window.lastStatus.key, window.lastStatus.vars);
    }

    try { localStorage.setItem('neutrixLang', lang); } catch (e) {}
    document.dispatchEvent(new CustomEvent('neutrix:langchange'));
}

function applyTheme(theme) {
    document.documentElement.setAttribute('data-theme', theme);
    try { localStorage.setItem('neutrixTheme', theme); } catch (e) {}
    updateThemeLabel();
}

themeBtn.addEventListener('click', () => {
    const isDark = document.documentElement.getAttribute('data-theme') === 'dark';
    applyTheme(isDark ? 'light' : 'dark');
});

langBtn.addEventListener('click', () => {
    applyLanguage(window.neutrixLang === 'English' ? 'Malayalam' : 'English');
});

(function init() {
    let savedTheme = 'light';
    let savedLang = 'English';
    try {
        savedTheme = localStorage.getItem('neutrixTheme') || 'light';
        savedLang = localStorage.getItem('neutrixLang') || 'English';
    } catch (e) {}
    document.documentElement.setAttribute('data-theme', savedTheme === 'dark' ? 'dark' : 'light');
    updateNav();
    applyLanguage(savedLang === 'Malayalam' ? 'Malayalam' : 'English');
})();